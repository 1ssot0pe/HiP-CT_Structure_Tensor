"""
certify_gate_scales.py -- pick the gate and peak-resolving scales by measurement
instead of pinning them.

What was wrong with the constants
---------------------------------
`sigma_rho_gated_field` carried

    GATE_HALF       = 14
    GATE_SIGMA_GRAD = 4.0     # "the only swept scale where c_s overtakes FA"
    DIR_SIGMA_GRAD  = 2.5     # "where HOST's second peak actually exists"

with a sweep table in the docstring as their justification. The values were
right and the evidence was real -- it just lived in a comment, so nothing
re-derived it, nothing checked it still held, and the numbers read as arbitrary
to anyone who had not read the docstring. This script runs that sweep and writes
the answer to `gate_scales.json`, which the gate then reads.

What CANNOT be done, and why
----------------------------
The obvious tidy-up is to delete these and reuse Stage 1's sigma. That destroys
the gate. Measured on the validated crossing phantom, at Stage 1's scale the
gate does not fire on a true crossing:

    sigma_grad   1.0    ->   c_s 0.216  vs  FA 0.664     no fire
    sigma_grad   4.0    ->   c_s 0.486  vs  FA 0.454     FIRES

The reason is geometric. A single fibre's gradients already lie in a plane, so
lambda3 is small; a crossing only lifts lambda3 once the differentiation scale
is coarse enough that gradients from BOTH fibre families land in the same
neighbourhood. Stage 1's sigma is the FIBRE scale by construction -- the scale
at which one fibre is best resolved -- which is precisely the scale at which two
fibres are still separate. They are different questions and they have different
answers, so the gate scale has to be certified on its own.

The certification
-----------------
THREE known-truth patches, two of which must NOT fire:

    crossing   centre of the localized crossing        must fire
    kissing    centre of the curved kissing pair       must NOT fire
    single     the SAME crossing volume, 45 voxels     must NOT fire
               off centre, where family 2 has tapered
               to exactly zero and only one remains

The single-fibre control is the one that makes this well-posed, and leaving it
out is not a small omission. Without it the criterion "maximise (c_s - FA) on
the crossing subject to the kissing staying silent" is MONOTONE in sigma_grad:
measured at half=14 the crossing margin runs -0.45, +0.03, +0.64, +0.69 at
sigma_grad 1, 4, 5, 6, so the pick simply walks to the largest scale swept, and
widening the sweep moves it again. That is the signature of a budget, not an
optimum -- the same read `loss_surface.py` records for `seed_density`.

The single fibre supplies the opposing force. Blur far enough and a lone fibre's
gradients stop lying in a plane too, so its c_s rises and it starts to route as
well; a gate that fires on single fibres routes the whole volume and separates
nothing. The certified quantity is therefore the DISCRIMINATIVE margin

    margin = (c_s - FA)_crossing  -  max[(c_s - FA)_kissing, (c_s - FA)_single]

which has an interior maximum: it is the gap between the case that must fire and
the nearest case that must not.

Taking the single-fibre control from the crossing volume itself, rather than
building a separate phantom, is deliberate -- same intensity statistics, same
tube spacing, same volume, differing only in the presence of the second family,
which is exactly the comparison the gate has to make.

    direction  among scales that resolve the crossing into exactly 2 peaks,
               minimise the angular error against the phantom's known
               directions. Peak COUNT alone is not enough -- a scale can split
               one fibre into two spurious lobes and score 2.

Both are properties of the METHOD and the fibre geometry, not of any particular
volume, so this is cached as a committed artifact and regenerated by hand rather
than recomputed every run.

Run
---
    python certify_gate_scales.py            # rewrites gate_scales.json
    python certify_gate_scales.py --show     # print the cached values only
"""

import argparse
import json
import os
import sys

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
for _p in (_ROOT, _HERE):
    sys.path.insert(0, _p)

from core.host_fod import analyse                                      # noqa: E402
from core.localized_phantoms import (raw_localized_crossing, raw_kissing,  # noqa: E402
                                CROSS_SHAPE, CROSS_R1, CROSS_TAPER,
                                CROSS_CAL_OFFSETS)

CACHE = os.path.join(_HERE, "gate_scales.json")

# The phantom the crossing is certified on: 40 deg separation, the narrowest
# crossing anything in this repo is validated at, so a scale that resolves it
# resolves the wider ones too.
CROSS_SEP_DEG = 40.0
CROSS_SPACING, CROSS_WIDTH = 12.0, 1.5
KISS_ARGS = (4.0, 0.028, 1.6, 1.6)
# Offset along the crossing volume's long axis (axis 1, length 200) to reach
# single-family tissue. Family 2 is windowed to r < CROSS_R1 (=20) and tapers to
# exactly zero by r = R1 + CROSS_TAPER (=28), so the first calibration offset
# (45) is comfortably outside the crossing zone.
SINGLE_OFFSET = int(CROSS_CAL_OFFSETS[0])

HALVES = (8, 10, 12, 14, 16)
# Swept past the point where the discriminative margin turns over, so the pick
# is visibly interior rather than resting on the edge of the box.
GATE_SIGMAS = (1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 5.0, 6.0, 8.0, 10.0)
DIR_SIGMAS = (1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0)
HOST_ORDER = 6


def _central_patch(vol, half):
    c = [s // 2 for s in vol.shape]
    return vol[tuple(slice(v - half, v + half + 1) for v in c)]


def _offset_patch(vol, half, offset, axis=1):
    """Patch centred `offset` voxels along `axis` from the volume centre."""
    c = [s // 2 for s in vol.shape]
    c[axis] += int(offset)
    return vol[tuple(slice(v - half, v + half + 1) for v in c)]


def _true_dirs(sep_deg=CROSS_SEP_DEG):
    """The crossing phantom's two fibre directions, in (x, y, z).

    `crossing_shape_3d._coords` builds its coordinates as (x, y, z) =
    (axis2, axis1, axis0), the same basis `host_fod.analyse` returns peaks in,
    so these compare directly with no reversal.
    """
    h = np.deg2rad(sep_deg / 2.0)
    return [np.array([np.cos(h), np.sin(h), 0.0]),
            np.array([np.cos(h), -np.sin(h), 0.0])]


def _angle_err_deg(dirs, truth):
    """Mean over true directions of the angle to the closest recovered one."""
    if not len(dirs):
        return np.nan
    errs = []
    for t in truth:
        errs.append(min(np.degrees(np.arccos(np.clip(abs(np.dot(d, t)), 0, 1)))
                        for d in dirs))
    return float(np.mean(errs))


def certify(verbose=True):
    """Sweep both phantoms and return the certified scales plus the evidence."""
    X = raw_localized_crossing(CROSS_SHAPE, CROSS_SEP_DEG, CROSS_SPACING,
                               CROSS_WIDTH, CROSS_R1, CROSS_TAPER)
    K = raw_kissing(*KISS_ARGS)

    # --- gate: (half, sigma_grad) --------------------------------------------
    if verbose:
        print("  sweeping the gate (c_s vs FA) on crossing, kissing AND single ...")
        print(f"    {'half':>4} {'sigma':>5} | {'cross':>15} | {'kiss':>15} | "
              f"{'single':>15} | {'discrim':>8}")
        print(f"    {'':>4} {'':>5} | {'c_s':>6}{'FA':>7}{'':>2} | "
              f"{'c_s':>6}{'FA':>7}{'':>2} | {'c_s':>6}{'FA':>7}{'':>2} | "
              f"{'margin':>8}")
    rows = []
    for half in HALVES:
        px = _central_patch(X, half)
        pk = _central_patch(K, half)
        ps = _offset_patch(X, half, SINGLE_OFFSET)
        for sg in GATE_SIGMAS:
            ms = [analyse(p, sigma_grad=sg, order=HOST_ORDER, peaks=False)
                  for p in (px, pk, ps)]
            if any(m is None for m in ms):
                continue
            mx, mk, msg = ms
            fires = [m["c_s"] > m["FA"] for m in ms]
            m_cross = float(mx["c_s"] - mx["FA"])
            m_neg = max(float(mk["c_s"] - mk["FA"]), float(msg["c_s"] - msg["FA"]))
            rows.append(dict(
                half=int(half), sigma_grad=float(sg),
                cross_cs=float(mx["c_s"]), cross_FA=float(mx["FA"]),
                kiss_cs=float(mk["c_s"]), kiss_FA=float(mk["FA"]),
                single_cs=float(msg["c_s"]), single_FA=float(msg["FA"]),
                cross_fires=bool(fires[0]), kiss_fires=bool(fires[1]),
                single_fires=bool(fires[2]),
                cross_margin=m_cross, discriminative_margin=float(m_cross - m_neg)))
            if verbose:
                f = ["Y" if v else "." for v in fires]
                print(f"    {half:4d} {sg:5.1f} | {mx['c_s']:6.3f}{mx['FA']:7.3f} "
                      f"{f[0]:>2} | {mk['c_s']:6.3f}{mk['FA']:7.3f} {f[1]:>2} | "
                      f"{msg['c_s']:6.3f}{msg['FA']:7.3f} {f[2]:>2} | "
                      f"{m_cross - m_neg:+8.3f}")

    # --- direction scale, swept for EVERY half -------------------------------
    # The two decisions are not separable, because they read the SAME patch. A
    # half chosen only for its gate margin can be one that resolves no peaks at
    # all: measured here, half=10 wins the gate outright (discriminative margin
    # +1.02 at sigma_grad 6) and then returns n_peaks=1 at every direction
    # scale swept -- a gate that fires on a crossing it cannot then decompose,
    # which is useless downstream. So a half is ADMISSIBLE only if it both gates
    # and resolves, and the pick is made over admissible halves only.
    truth = _true_dirs()
    if verbose:
        print(f"\n  sweeping the peak-resolving scale for every half ...")
        print(f"    {'half':>4} {'sigma':>6} {'n_peaks':>8} {'sep':>7} "
              f"{'amp2':>6} {'ang err':>8}")
    dir_rows = []
    for half in HALVES:
        px = _central_patch(X, half)
        for sg in DIR_SIGMAS:
            m = analyse(px, sigma_grad=sg, order=HOST_ORDER)
            if m is None:
                continue
            err = (_angle_err_deg(m["dirs"][:2], truth) if m["n_peaks"] >= 2
                   else np.nan)
            dir_rows.append(dict(
                half=int(half), sigma_grad=float(sg), n_peaks=int(m["n_peaks"]),
                sep=float(m["sep"]) if np.isfinite(m["sep"]) else None,
                amp2=float(m["amp2"]) if np.isfinite(m["amp2"]) else None,
                angle_err_deg=None if not np.isfinite(err) else float(err)))
            if verbose and m["n_peaks"] >= 2:
                print(f"    {half:4d} {sg:6.1f} {m['n_peaks']:8d} "
                      f"{m['sep']:7.1f} {m['amp2']:6.2f} {err:8.1f}")

    # --- the joint pick ------------------------------------------------------
    gate_ok = [r for r in rows if r["cross_fires"] and not r["kiss_fires"]
               and not r["single_fires"]]
    dir_ok = [r for r in dir_rows
              if r["n_peaks"] == 2 and r["angle_err_deg"] is not None]
    if not gate_ok:
        raise RuntimeError(
            "no (half, sigma_grad) fires on the crossing while staying silent on "
            "BOTH the kissing pair and single-fibre tissue -- the gate cannot be "
            "certified on these phantoms. Widen HALVES/GATE_SIGMAS before "
            "trusting any value.")
    if not dir_ok:
        raise RuntimeError(
            "no (half, sigma_grad) resolves the 40 deg crossing into exactly 2 "
            "peaks -- the peak-resolving scale cannot be certified.")

    admissible = sorted(set(r["half"] for r in gate_ok)
                        & set(r["half"] for r in dir_ok))
    if not admissible:
        raise RuntimeError(
            f"no half both gates and resolves. Halves that gate: "
            f"{sorted(set(r['half'] for r in gate_ok))}; halves that resolve 2 "
            f"peaks: {sorted(set(r['half'] for r in dir_ok))}. The two "
            f"requirements do not overlap on this phantom.")

    best_per_half = {}
    for h in admissible:
        g = max((r for r in gate_ok if r["half"] == h),
                key=lambda r: r["discriminative_margin"])
        d = min((r for r in dir_ok if r["half"] == h),
                key=lambda r: r["angle_err_deg"])
        best_per_half[h] = (g, d)
    if verbose:
        print(f"\n  admissible halves (gate AND resolve): {admissible}")
        for h in admissible:
            g, d = best_per_half[h]
            print(f"    half={h:2d}  gate sigma={g['sigma_grad']:g} "
                  f"margin {g['discriminative_margin']:+.3f}  |  dir sigma="
                  f"{d['sigma_grad']:g} err {d['angle_err_deg']:.1f} deg")

    half_pick = max(admissible,
                    key=lambda h: best_per_half[h][0]["discriminative_margin"])
    gate, best_dir = best_per_half[half_pick]

    # An optimum on the edge of the swept box is not an optimum, it is the box.
    # Say so rather than writing the value out as though it were certified.
    edge = []
    if gate["sigma_grad"] in (GATE_SIGMAS[0], GATE_SIGMAS[-1]):
        edge.append(f"gate sigma_grad={gate['sigma_grad']:g}")
    if best_dir["sigma_grad"] in (DIR_SIGMAS[0], DIR_SIGMAS[-1]):
        edge.append(f"dir sigma_grad={best_dir['sigma_grad']:g}")
    if half_pick in (HALVES[0], HALVES[-1]):
        edge.append(f"half={half_pick}")
    if edge and verbose:
        print(f"\n  WARNING: the pick sits on the sweep boundary ({', '.join(edge)}) "
              f"-- the true optimum is probably outside the box. Widen the sweep.")
    gate["on_sweep_boundary"] = bool(edge)

    out = dict(
        gate_half=int(gate["half"]),
        gate_sigma_grad=float(gate["sigma_grad"]),
        dir_sigma_grad=float(best_dir["sigma_grad"]),
        host_order=int(HOST_ORDER),
        evidence=dict(
            criterion_gate="max discriminative margin = (c_s-FA)_crossing - "
                           "max[(c_s-FA)_kissing, (c_s-FA)_single], subject to "
                           "firing on the crossing and on neither negative case",
            criterion_dir="min angular error against known directions, among "
                          "scales resolving exactly 2 peaks",
            gate_discriminative_margin=float(gate["discriminative_margin"]),
            gate_cross_margin=float(gate["cross_margin"]),
            gate_on_sweep_boundary=bool(gate["on_sweep_boundary"]),
            gate_cross_cs=gate["cross_cs"], gate_cross_FA=gate["cross_FA"],
            gate_kiss_cs=gate["kiss_cs"], gate_kiss_FA=gate["kiss_FA"],
            gate_single_cs=gate["single_cs"], gate_single_FA=gate["single_FA"],
            dir_angle_err_deg=best_dir["angle_err_deg"],
            dir_sep_deg=best_dir["sep"],
            admissible_halves=[int(h) for h in admissible],
            phantom=dict(sep_deg=CROSS_SEP_DEG, spacing=CROSS_SPACING,
                         width=CROSS_WIDTH, kissing=list(KISS_ARGS),
                         single_offset=int(SINGLE_OFFSET)),
            n_usable_gate=len(gate_ok), n_swept_gate=len(rows),
            gate_sweep=rows, dir_sweep=dir_rows))
    return out


def load_gate_scales(path=CACHE):
    """Read the cached certification. Raises if it has not been run.

    Deliberately NOT falling back to the old literals. A silent fallback would
    reintroduce exactly the hardcoding this replaces, and worse, would hide that
    the certification never ran.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"{path} not found -- run:\n"
            f"    python 1_sigma_rho_selection/certify_gate_scales.py\n"
            f"to certify the gate and peak-resolving scales before running the "
            f"pipeline.")
    with open(path) as f:
        return json.load(f)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="certify the gate scales")
    ap.add_argument("--show", action="store_true", help="print the cache only")
    ap.add_argument("--out", default=CACHE)
    a = ap.parse_args()

    if a.show:
        g = load_gate_scales(a.out)
        print(json.dumps({k: v for k, v in g.items() if k != "evidence"}, indent=2))
        sys.exit(0)

    print("=" * 78)
    print("GATE SCALE CERTIFICATION -- on phantoms with known truth")
    print("=" * 78)
    g = certify()
    print("\n" + "-" * 78)
    print(f"  gate       half={g['gate_half']}, sigma_grad="
          f"{g['gate_sigma_grad']:g}   (discriminative margin "
          f"{g['evidence']['gate_discriminative_margin']:+.3f}; crossing fires at "
          f"{g['evidence']['gate_cross_margin']:+.3f}, kissing and single silent)")
    print(f"  direction  sigma_grad={g['dir_sigma_grad']:g}   "
          f"(angular error {g['evidence']['dir_angle_err_deg']:.1f} deg, "
          f"sep {g['evidence']['dir_sep_deg']:.1f} deg)")
    with open(a.out, "w") as f:
        json.dump(g, f, indent=2)
    print(f"  wrote {a.out}")
    print("=" * 78)
